    fun getString(key: String, language: String): String {
        val strings = when (language) {
            "Русский" -> ruStrings
            "Deutsch" -> deStrings
            "Español" -> esStrings
            "Français" -> frStrings
            "Português" -> ptStrings
            else -> enStrings
        }
        return strings[key] ?: enStrings[key] ?: key
    }

